import {execFileSync} from 'node:child_process';
import {existsSync,readFileSync,readdirSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const modules=new Map();
for(const GOOS of ['darwin','windows']) {
  const output=execFileSync('go',['list','-tags','desktop,production,wv2runtime.browser','-deps','-f','{{if .Module}}{{if not .Module.Main}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}{{end}}','.'],{
    cwd:root,encoding:'utf8',env:{...process.env,GOOS,GOARCH:'arm64',CGO_ENABLED:GOOS==='darwin'?'1':'0'}
  });
  for(const line of output.trim().split('\n').filter(Boolean)) {
    const [Path,Version,Dir]=line.split('\t');modules.set(Path,{Path,Version,Dir});
  }
}
function licenseFiles(dir,relative='') {
  return readdirSync(path.join(dir,relative),{withFileTypes:true}).flatMap(entry=>{
    const file=path.join(relative,entry.name);
    if(entry.isDirectory()&&!entry.name.startsWith('.'))return licenseFiles(dir,file);
    return entry.isFile()&&/^(licen[cs]e|copying|notice)(\..+|-.*)?$/i.test(entry.name)?[file]:[];
  }).sort();
}
const goroot=execFileSync('go',['env','GOROOT'],{encoding:'utf8'}).trim();
let text='Third-party notices\nGenerated by scripts/generate-third-party-notices.mjs.\n\n';
const goLicense=[path.join(goroot,'LICENSE'),path.join(goroot,'../LICENSE')].find(existsSync);
if(!goLicense)throw new Error('Go toolchain LICENSE not found');
text+='Go standard library and runtime\n'+readFileSync(goLicense,'utf8')+'\n';
for(const [name,module] of [...modules].sort(([a],[b])=>a.localeCompare(b,'en'))) {
  const files=licenseFiles(module.Dir);
  if(!files.length)throw new Error('Missing license: '+name);
  text+='\n'+name+' '+module.Version+'\n'+'='.repeat(72)+'\n';
  for(const file of files)text+='\n'+file+'\n'+readFileSync(path.join(module.Dir,file),'utf8').trimEnd()+'\n';
}
writeFileSync(path.join(root,'internal/app/webui/third-party-notices.txt'),text);
console.log('Updated notices for '+modules.size+' native dependencies.');
